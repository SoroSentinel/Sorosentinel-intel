#!/bin/sh
# Generates each repo's AGENTS.md (docs/agents/core.md + its profile) and
# copies the canonical docs into Scan and Guard (docs/project_structure.md §2.1).
#
# Usage: scripts/sync-docs.sh [--check]
#   (no flag)  write files into this repo and the sibling repos
#   --check    write nothing; exit 1 if any reachable target is out of date
#              (sibling repos that are not checked out are skipped)
#
# Sibling repo paths default to ../Sorosentinel-guard and ../Sorosentinel-scan;
# override with GUARD_REPO / SCAN_REPO. Opening PRs in those repos stays manual.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
GUARD_REPO="${GUARD_REPO:-$ROOT/../Sorosentinel-guard}"
SCAN_REPO="${SCAN_REPO:-$ROOT/../Sorosentinel-scan}"
DOCS="PRD.md ARCHITECTURE.md ARCHITECTURE_ESSENTIALS.md project_structure.md"

MODE="write"
case "${1:-}" in
  "") ;;
  --check) MODE=check ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
STALE=0

# emit <dest> <generated file>: write it, or compare it in --check mode.
emit() {
  if [ "$MODE" = check ]; then
    if ! cmp -s "$2" "$1"; then
      echo "out of date: $1" >&2
      STALE=1
    fi
  else
    mkdir -p "$(dirname "$1")"
    cp "$2" "$1"
  fi
}

agents_md() { # <profile name> <out>
  {
    echo "<!-- GENERATED by sorosentinel-intel/scripts/sync-docs.sh from docs/agents/core.md + docs/agents/profile-$1.md. Edit those, not this file. -->"
    echo
    awk -v pf="$ROOT/docs/agents/profile-$1.md" '
      $0 == "{{PROFILE}}" { while ((getline line < pf) > 0) print line; next }
      { print }
    ' "$ROOT/docs/agents/core.md"
  } > "$2"
}

doc_copy() { # <relative doc path> <out>
  {
    echo "<!-- GENERATED: edit sorosentinel-intel/docs/$1, then run scripts/sync-docs.sh. -->"
    echo
    cat "$ROOT/docs/$1"
  } > "$2"
}

agents_md intel "$TMP/AGENTS.intel.md"
emit "$ROOT/AGENTS.md" "$TMP/AGENTS.intel.md"

for pair in "guard:$GUARD_REPO" "scan:$SCAN_REPO"; do
  name=${pair%%:*}
  repo=${pair#*:}
  # A worktree's .git is a file, not a directory; -d would skip it and --check
  # would then report clean for a sibling nobody looked at.
  if [ ! -e "$repo/.git" ]; then
    if [ "$MODE" = check ]; then
      echo "skip: $name repo not found at $repo" >&2
      continue
    fi
    # the override is GUARD_REPO / SCAN_REPO, not guard_REPO
    var=$(printf '%s' "$name" | tr 'abcdefghijklmnopqrstuvwxyz' 'ABCDEFGHIJKLMNOPQRSTUVWXYZ')_REPO
    echo "error: $name repo not found at $repo (set $var)" >&2
    exit 1
  fi
  agents_md "$name" "$TMP/AGENTS.$name.md"
  emit "$repo/AGENTS.md" "$TMP/AGENTS.$name.md"
  for doc in $DOCS; do
    doc_copy "$doc" "$TMP/$name.$doc"
    emit "$repo/docs/$doc" "$TMP/$name.$doc"
  done
  for adr in "$ROOT"/docs/adr/*.md; do
    [ -e "$adr" ] || continue
    rel="adr/$(basename "$adr")"
    doc_copy "$rel" "$TMP/$name.adr.$(basename "$adr")"
    emit "$repo/docs/$rel" "$TMP/$name.adr.$(basename "$adr")"
  done
done

if [ "$MODE" = check ] && [ "$STALE" -ne 0 ]; then
  echo "run scripts/sync-docs.sh to regenerate" >&2
  exit 1
fi
